func redFinding(rule string, reason Text, words []string, title Text) Finding {
	vars := baseVars(lits(words))
	return Finding{Rule: rule, Level: Red, Reason: reason, Title: render(title, vars), Words: words}
}

// evalRule looks up the rule for a command and applies its check and the
// fixed protections.
func (c *Classifier) evalRule(scope string, ws []Word) Finding {
	f := c.evalWith(c.rules, scope, ws)
	if len(c.rules.user) == 0 || f.Special {
		return f
	}
	// The fixed protections are judged with the built-in rules alone, so a
	// user rule can lower a level but never a protection.
	b := c.evalWith(ruleSet{builtin: c.rules.builtin}, scope, ws)
	switch {
	case b.Special:
		f.Level, f.Special, f.Op, f.Reason = Red, true, nil, Join(b.Reason, f.Reason)
		setIdentity(scope, ws, &f)
	case f.Level < Red && b.Level != Green && hasDynamic(ws):
		f.Level, f.Special, f.Op = Red, true, nil
		f.Reason = Join(reason("arguments only known on the phone could name ADBuddy or a critical app"), f.Reason)
	}
	return f
}

func hasDynamic(ws []Word) bool {
	for _, w := range ws {
		if w.Dynamic {
			return true
		}
	}
	return false
}

// evalWith evaluates one command with a rule set.
func (c *Classifier) evalWith(rs ruleSet, scope string, ws []Word) Finding {
	vals := values(ws)
	name := ws[0].Value
	if scope == "adb" && strings.HasPrefix(name, "wait-for-") {
		name = "wait-for"
	}
	r, ok := rs.find(scope, name, subOf(ws))
	if !ok {
		f := redFinding("unknown", reason("unknown command"), vals, textUnknown)
		applySpecial(scope, ws, &f)
		return f
	}
	vars := baseVars(ws)
	f := Finding{Rule: r.ID, Level: r.level, UI: r.UI, Words: vals}
	if !r.AnyArgs {
		for _, w := range ws[1:] {
			if w.Dynamic {
				f.Level, f.Reason = Red, reason("arguments only known on the phone")
				f.Title = render(textDynamic, vars)
				applySpecial(scope, ws, &f)
				return f
			}
		}
	}
	if r.Check != "" && r.AnyArgs && hasDynamic(ws[1:]) {
		// Checks look for dangerous words; a word only known on the phone
		// could be one of them.
		f.Level, f.Reason = Red, reason("arguments only known on the phone")
		f.Title = render(textDynamic, vars)
		applySpecial(scope, ws, &f)
		return f
	}
	if r.Check != "" {
		res := checks[r.Check](ws)
		if res.level > f.Level {
			f.Level, f.Reason = res.level, res.reason
		}
		for k, v := range res.vars {
			vars[k] = display([]string{v})
		}
		if res.op != nil && f.Level != Red {
			f.Op = res.op
		}
	}
	f.Title = titleFor(r.Title, vars, f.Level == Red && r.level != Red)
	applySpecial(scope, ws, &f)
	return f
}

var placeholder = regexp.MustCompile(`\{[a-z0-9]+\}`)

// titleFor renders a rule title. Placeholders of the template without a value
// are dropped (the values themselves are never scanned, so an argument such
// as "{x}" stays as typed); if a check rejected the arguments, the generic
// "Run: {cmd}" is clearer.
func titleFor(t Text, vars map[string]string, rejected bool) Text {
	var missing []string
	for _, m := range placeholder.FindAllString(t.EN+t.ES, -1) {
		if _, ok := vars[m[1:len(m)-1]]; !ok {
			missing = append(missing, m[1:len(m)-1])
		}
	}
	if len(missing) == 0 {
		return render(t, vars)
	}
	if rejected {
		return render(Text{EN: "Run: {cmd}", ES: "Ejecutar: {cmd}"}, vars)
	}
	const gap = "\x00"
	withGaps := map[string]string{}
	for k, v := range vars {
		withGaps[k] = v
	}
	for _, k := range missing {
		withGaps[k] = gap
	}
	out := render(t, withGaps)
	clean := func(s string) string {
		s = strings.ReplaceAll(s, " "+gap, "")
		s = strings.ReplaceAll(s, gap+" ", "")
		return strings.ReplaceAll(s, gap, "")
	}
	return Text{EN: clean(out.EN), ES: clean(out.ES)}
}

// subOf is the first argument that is not an option (skipping "--user N").
// A dynamic word up to the subcommand makes it unknown: on the phone an
// unquoted $(…) may split into options and a different verb.
func subOf(ws []Word) string {
	sub, _ := subAt(ws)
	return sub
}

// subAt is subOf plus the subcommand's index in ws (-1 if unknown).
func subAt(ws []Word) (string, int) {
	for i := 1; i < len(ws); i++ {
		if ws[i].Dynamic {
			return "", -1
		}
		v := ws[i].Value
		if v == "--user" {
			i++
			if i < len(ws) && ws[i].Dynamic {
				return "", -1
			}
			continue
		}
		if strings.HasPrefix(v, "-") {
			continue
		}
		return v, i
	}
	return "", -1
}
