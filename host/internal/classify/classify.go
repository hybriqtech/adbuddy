// Op is a change the host knows how to precheck and invert (spec §4.3).
// Kinds: settings-put, pm-disable, pm-uninstall-user, appops-set, deviceidle,
// mv, mkdir, new-file, adb-install, adb-push.
type Op struct {
	Kind string            `json:"kind"`
	Args map[string]string `json:"args"`
}

// Finding is the verdict for one fragment of a command.
type Finding struct {
	Rule    string `json:"rule"`
	Level   Level  `json:"level"`
	Title   Text   `json:"title"`
	Reason  Text   `json:"reason,omitempty"`
	Special bool   `json:"special,omitempty"` // always 🔴: may cut the connection or affect ADBuddy
	// AppChannel: it touches the app's own channel or private files (content on its authority, run-as, am start or
	// broadcast naming it). The host never lifts these, YOLO or not.
	AppChannel bool     `json:"appChannel,omitempty"`
	UI         bool     `json:"ui,omitempty"`
	Op         *Op      `json:"op,omitempty"`
	PCWrite    *PCWrite `json:"pcWrite,omitempty"` // adb pull and adb bugreport: where it writes on the PC
	Words      []string `json:"words"`
}

// PCWrite is where an adb command writes on the PC (adb pull, adb bugreport).
// The classifier cannot know the agent's working directory: the daemon checks
// these targets against the agent's environment (see daemon.checkPCWrites).
// It is filled whatever rule matched, so a user rule cannot hide it.
type PCWrite struct {
	Cmd     string   `json:"cmd"`               // "pull" or "bugreport"
	Targets []string `json:"targets,omitempty"` // relative to the working directory; the directory itself is always written
	Reason  Text     `json:"reason,omitempty"`  // why the targets are unsafe or unknown; empty if they look safe
}

// Result is the verdict for a whole adb command: the highest level wins.
type Result struct {
	Level      Level     `json:"level"`
	Primary    Finding   `json:"primary"` // the first fragment with the highest level
	Findings   []Finding `json:"findings"`
	Special    bool      `json:"special,omitempty"`
	AppChannel bool      `json:"appChannel,omitempty"`
	Op         *Op       `json:"op,omitempty"` // the command's only change with a known inverse, if any
	PCWrites   []PCWrite `json:"pcWrites,omitempty"`
}

// Description is the one-line description of the command, generated by the
// rules and never by the agent.
func (r Result) Description(lang string) string { return r.Primary.Title.In(lang) }

// Detail lists why the command needs confirmation, one reason per line.
func (r Result) Detail(lang string) string {
	var lines []string
	seen := map[string]bool{}
	for _, f := range r.Findings {
		if f.Level != Red {
			continue
		}
		line := f.Title.In(lang)
		if !f.Reason.Empty() {
			line += " (" + Printable(f.Reason.In(lang)) + ")"
		}
		if !seen[line] {
			seen[line] = true
			lines = append(lines, line)
		}
	}
	return strings.Join(lines, "\n")
}

// Classifier holds the rules: user rules first, then the built-in ones.
type Classifier struct {
	rules ruleSet
}

// New builds a classifier from the built-in rules plus the user's rules.yaml
// content (nil or empty for none).
func New(userYAML []byte) (*Classifier, error) {
	builtin, err := builtinRules()
	if err != nil {
		return nil, err
	}
	user, err := parseRules(userYAML, true)
	if err != nil {
		return nil, err
	}
	return &Classifier{rules: ruleSet{user: user, builtin: builtin}}, nil
}

// UserRuleCount is how many rules came from the user's rules.yaml.
func (c *Classifier) UserRuleCount() int { return len(c.rules.user) }

// Classify classifies adb arguments with the global options already removed
// (see SplitGlobal).
func (c *Classifier) Classify(argv []string) Result {
	return namesTheChannel(namesTheApp(aggregate(c.classifyAdb(argv)), argv), argv)
}

// appAuthority, appProviderClass: the app's ContentProvider (handshake and token).
const (
	appAuthority     = "tech.hybriq.adbuddy.bridge"
	appProviderClass = "tokenprovider"
)

var channelVerb = regexp.MustCompile(`(^|[^a-z0-9_])(content|run-as)([^a-z0-9_]|$)`)

// namesTheChannel marks AppChannel on a 🔴 that is already special for another
// rule (a pipe into sh, eval, an assignment before app_process…) when the line
// itself, as a literal string, names the app's channel: its authority, its
// ContentProvider class, or the package together with content or run-as. Only
// the literal chain is seen: an opaque script (a file on the phone, eval of
// "$(cat …)") is not, and that limit is documented (docs/safety.md). It never
// changes the level and not the findings, and does not mark force-stop or kill
// of the package (ruling T4).
func namesTheChannel(r Result, argv []string) Result {
	if r.Level != Red || r.AppChannel {
		return r
	}
	s := strings.ToLower(strings.Join(argv, " "))
	unquote := strings.NewReplacer(`'`, "", `"`, "", `\`, "")
	for range 4 {
		for _, t := range []string{s, unquote.Replace(s)} {
			if strings.Contains(t, appAuthority) || strings.Contains(t, appProviderClass) ||
				(strings.Contains(t, ADBuddyPackage) && channelVerb.MatchString(t)) {
				r.AppChannel = true
				return r
			}
		}
		d := strings.ToLower(percentDecode(s))
		if d == s {
			break
		}
		s = d
	}
	return r
}

// namesTheApp is a defence in depth: a 🔴 that is not special but names the
// app in its raw text (hybriq or adbudd, in any case, after decoding %xx and
// ignoring quotes and backslashes) becomes special. A path to the app channel
// that the rules miss then still warns and offers no "allow during the
// session". It never changes a 🟢 or a 🟡.
func namesTheApp(r Result, argv []string) Result {
	if r.Level != Red || r.Special || !mentionsAppText(strings.Join(argv, " ")) {
		return r
	}
	r.Special = true
	// A path to the channel that the rules missed: fail closed, the host does not lift it under YOLO either.
	r.AppChannel = true
	r.Findings = append(r.Findings, redFinding("adbuddy.mention", reason("names the ADBuddy app"), argv, textMentionsApp))
	r.Findings[len(r.Findings)-1].Special = true
	r.Findings[len(r.Findings)-1].AppChannel = true
	return r
}

// mentionsAppText looks for the app's name in s, decoding %xx until nothing
// changes (a few rounds at most).
func mentionsAppText(s string) bool {
	unquote := strings.NewReplacer(`'`, "", `"`, "", `\`, "")
	s = strings.ToLower(s)
	for range 4 {
		for _, t := range []string{s, unquote.Replace(s)} {
			if strings.Contains(t, "hybriq") || strings.Contains(t, "adbudd") {
				return true
			}
		}
		d := strings.ToLower(percentDecode(s))
		if d == s {
			break
		}
		s = d
	}
	return false
}

func (c *Classifier) classifyAdb(argv []string) []Finding {
	switch {
	case len(argv) == 0:
		return []Finding{{Rule: "adb.help", Level: Green, Title: Text{EN: "Show adb help", ES: "Mostrar la ayuda de adb"}}}
	case argv[0] == "shell":
		return c.classifyShellCommand(argv[1:], true)
	case argv[0] == "exec-out":
		return c.classifyExecOut(argv[1:])
	case argv[0] == "exec-in":
		// adb pipes the agent's stdin into the command: decided before the
		// rules, so a user rule cannot lower it.
		return []Finding{unanalysable("shell.stdin", reason("exec-in: the command reads what comes through stdin, which is not analysed"), argv, textStdinCmd)}
	case argv[0] == "abb_exec" || argv[0] == "abb":
		// exec-in for a system service: adb hands it the agent's stdin (adb
		// install streams the APK this way). Before the rules, like exec-in.
		return []Finding{unanalysable("shell.stdin", reason("abb_exec and abb: the system service reads what comes through stdin, which is not analysed"), argv, textStdinCmd)}
	case strings.HasPrefix(argv[0], "wait-for-") && len(argv) > 1:
		// adb runs the rest of the line once the device is there.
		return append([]Finding{c.evalRule("adb", lits(argv[:1]))}, c.classifyAdb(argv[1:])...)
	}
	f := c.evalRule("adb", lits(argv))
	if argv[0] == "pull" || argv[0] == "bugreport" {
		targets, reason := pcTargets(lits(argv))
		f.PCWrite = &PCWrite{Cmd: argv[0], Targets: targets, Reason: reason}
	}
	return []Finding{f}
}

// classifyExecOut rebuilds the line exactly as adb does for exec-out: the
// first argument as is and every other one single-quoted (adb's escape_arg).
func (c *Classifier) classifyExecOut(args []string) []Finding {
	if len(args) == 0 {
		return []Finding{interactive(args)}
	}
	line := args[0]
	for _, a := range args[1:] {
		line += " " + adbEscapeArg(a)
	}
	if strings.TrimSpace(line) == "" {
		return []Finding{interactive(args)}
	}
	return c.classifyScript(line, scope{})
}

// interactive is adb shell or exec-out without a command: the commands come
// through the agent's stdin, which the daemon forwards and nobody sees. Allowed
// for the session, it would allow whatever comes next (A4-1): it is special.
func interactive(args []string) Finding {
	return unanalysable("shell.interactive", reason("the commands come through stdin and are not analysed"), args, textInteractive)
}

// adbEscapeArg quotes like adb's escape_arg: always single quotes, with each
// ' written as close-quote, backslash-quote, open-quote.
func adbEscapeArg(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

// classifyShellCommand handles `adb shell [options] [command…]`. adb joins
// the command words with spaces, without quoting ("just like ssh"), and the
// phone runs them with `sh -c`, so the joined line is what gets parsed.
func (c *Classifier) classifyShellCommand(args []string, options bool) []Finding {
	i := 0
	for options && i < len(args) && strings.HasPrefix(args[i], "-") {
		switch args[i] {
		case "-n", "-T", "-t", "-tt", "-x":
			i++
		case "-e":
			i += 2
		default:
			// adb reads its options with getopt (-nt, --): what runs, maybe
			// an interactive shell, is not known.
			return []Finding{unanalysable("shell.option", reason("unknown adb shell option {arg}", "arg", args[i]), args, textUnknown)}
		}
	}
	if i > len(args) {
		i = len(args)
	}
	line := strings.Join(args[i:], " ")
	if strings.TrimSpace(line) == "" {
		return []Finding{interactive(args)}
	}
	return c.classifyScript(line, scope{})
}

// aggregate combines fragment findings: highest level wins; more than one
// change with an inverse in the same command is 🔴, because prechecks run
// before the whole command and could not see the first change.
func aggregate(fs []Finding) Result {
	if len(fs) == 0 {
		fs = []Finding{{Rule: "shell.noop", Level: Green, Title: Text{EN: "Run an empty command", ES: "Ejecutar un comando vacío"}}}
	}
	var ops []*Op
	for _, f := range fs {
		if f.Op != nil {
			ops = append(ops, f.Op)
		}
	}
	if len(ops) > 1 {
		var words []string
		for _, f := range fs {
			words = append(words, f.Words...)
		}
		fs = append([]Finding{redFinding("multi-change", reason("several changes in one command: run them one by one to be able to undo them"), words, textMultiChange)}, fs...)
		ops = nil
	}
	r := Result{Findings: fs, Primary: fs[0]}
	for _, f := range fs {
		if f.Level > r.Level {
			r.Level = f.Level
			r.Primary = f
		}
		if f.Special {
			r.Special = true
		}
		if f.AppChannel {
			r.AppChannel = true
		}
		if f.PCWrite != nil {
			r.PCWrites = append(r.PCWrites, *f.PCWrite)
		}
	}
	if len(ops) == 1 {
		r.Op = ops[0]
	}
	return r
}

// Global holds the adb global options that precede the command.
type Global struct {
	Serial    string   // -s SERIAL
	Forbidden []string // options ADBuddy does not allow (other devices or servers)
	Pass      []string // harmless options passed through
}

// SplitGlobal separates adb's global options from the command. Options that
// would reach another device or another adb server are Forbidden.
func SplitGlobal(argv []string) (Global, []string) {
	var g Global
	i := 0
	for i < len(argv) && strings.HasPrefix(argv[i], "-") {
		a := argv[i]
		switch {
		case a == "-s" && i+1 < len(argv):
			g.Serial = argv[i+1]
			i += 2
			continue
		case strings.HasPrefix(a, "-s") && len(a) > 2:
			g.Serial = a[2:]
		case a == "--exit-on-write-error":
			g.Pass = append(g.Pass, a)
		case a == "-t" || a == "-H" || a == "-P" || a == "-L" || a == "--one-device":
			g.Forbidden = append(g.Forbidden, a)
			i += 2
			continue
		default: // -a, -d, -e, -tID, -Hhost, -Pport, -Lsocket and anything unknown
			g.Forbidden = append(g.Forbidden, a)
		}
		i++
	}
	if i > len(argv) {
		i = len(argv)
	}
	return g, argv[i:]
}

// Word is one argument of a command. Dynamic words contain expansions,
// substitutions or globs whose value is only known on the phone.
type Word struct {
	Value   string
	Dynamic bool
	node    *syntax.Word // the parsed word, if it came from the shell line
}

func lits(ss []string) []Word {
	ws := make([]Word, len(ss))
	for i, s := range ss {
		ws[i] = Word{Value: s}
	}
	return ws
}

func values(ws []Word) []string {
	out := make([]string, len(ws))
	for i, w := range ws {
		out[i] = w.Value
	}
	return out
}

// display shortens a command, or one of its words, for titles: escaped,
// runs of blanks of any mix compacted (compact: padding cannot push the rest
// out of the title) and cut to 80 runes. The whole command is in the question's raw
// command.
func display(ws []string) string {
	s := compact(strings.Join(ws, " "), func(b *strings.Builder, r rune) { b.WriteString(Printable(string(r))) })
	if utf8.RuneCountInString(s) > 80 {
		r := []rune(s)
		s = string(r[:79]) + "…"
	}
	return s
}

// Printable escapes what could hide or rewrite text on a terminal (hidden):
// control characters (ANSI sequences start with one), DEL, bidirectional
// overrides, zero-width characters, spaces other than U+0020, fillers and
// combining marks. Everything the agent chose that a person will
// read (titles, the raw command, the journal view) goes through it.
func Printable(s string) string {
	var b strings.Builder
	for _, r := range s {
		switch {
		case r == '\n':
			b.WriteString(`\n`)
		case r == '\r':
			b.WriteString(`\r`)
		case r == '\t':
			b.WriteString(`\t`)
		case hidden(r):
			escape(&b, r)
		default:
			b.WriteRune(r)
		}
	}
	return b.String()
}

func baseVars(ws []Word) map[string]string {
	vals := values(ws)
	vars := map[string]string{"cmd": display(vals), "args": ""}
	if len(vals) > 1 {
		vars["args"] = display(vals[1:])
	}
	for i, v := range vals {
		vars[strconv.Itoa(i)] = display([]string{v}) // A4-3: no endless title nor detail line
	}
	return vars
}

